name = "Python"

# Concatenation
print(name + " Programming")

# Repetition
print(name * 2)

# Indexing
print(name[0])

# Slicing
print(name[1:4])

# Length
print(len(name))

# Membership
print("P" in name)

# Uppercase
print(name.upper())


# Implicit Conversion
a = 10
b = 5.5

c = a + b

print(c)
print(type(c))

# Explicit Conversion
x = "100"

x = int(x)

print(x)
print(type(x))